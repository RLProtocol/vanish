// Converts the snarkjs verification key into the groth16-solana constant used on-chain.
// Encoding (alt_bn128 / EIP-197): field elements big-endian; G2 = x.c1 | x.c0 | y.c1 | y.c0.
//   node scripts/vk-to-rust.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const vk = JSON.parse(fs.readFileSync(path.join(root, "build/circuits/verification_key.json"), "utf8"));

const be32 = (dec) => {
  const hex = BigInt(dec).toString(16).padStart(64, "0");
  return hex.match(/../g).map((b) => `0x${b}`);
};
const g1 = (p) => [...be32(p[0]), ...be32(p[1])];
const g2 = (p) => [...be32(p[0][1]), ...be32(p[0][0]), ...be32(p[1][1]), ...be32(p[1][0])];
const arr = (bytes) => `[\n        ${bytes.join(", ")},\n    ]`;

const out = `// Generated by scripts/vk-to-rust.mjs from build/circuits/verification_key.json. Do not edit.
use groth16_solana::groth16::Groth16Verifyingkey;

pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};

pub const VERIFYINGKEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: ${arr(g1(vk.vk_alpha_1))},
    vk_beta_g2: ${arr(g2(vk.vk_beta_2))},
    vk_gamme_g2: ${arr(g2(vk.vk_gamma_2))},
    vk_delta_g2: ${arr(g2(vk.vk_delta_2))},
    vk_ic: &[
${vk.IC.map((p) => `        ${arr(g1(p)).replace(/\n {4}/g, "\n        ")},`).join("\n")}
    ],
};
`;

const dest = path.join(root, "programs/solmix/src/verifying_key.rs");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(root, dest)} (${vk.nPublic} public inputs, ${vk.IC.length} IC points)`);
